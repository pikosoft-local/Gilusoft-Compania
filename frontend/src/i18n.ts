export function getDefaultTranslations(language: Language) {
  const keys = new Set(Object.values(translations).flatMap((bundle) => Object.keys(bundle)))
  return Object.fromEntries([...keys].map((key) => [
    key,
    language === 'pl' ? key : translations[language][key] ?? key,
  ]))
}

function getInitialLanguage(): Language {
  const savedLanguage = window.localStorage.getItem('gilusoft-language')
  if (savedLanguage && supportedLanguages.includes(savedLanguage as Language)) {
    return savedLanguage as Language
  }
  const browserLanguage = window.navigator.language.slice(0, 2)
  return supportedLanguages.includes(browserLanguage as Language)
    ? (browserLanguage as Language)
    : 'pl'
}

void i18n.use(initReactI18next).init({
  resources: Object.fromEntries(
    supportedLanguages.map((language) => [
      language,
      { translation: translations[language] },
    ]),
  ),
  lng: getInitialLanguage(),
  fallbackLng: 'pl',
  interpolation: { escapeValue: false },
})

i18n.on('languageChanged', (language) => {
  if (supportedLanguages.includes(language as Language)) {
    window.localStorage.setItem('gilusoft-language', language)
    document.documentElement.lang = language
  }
})

document.documentElement.lang = i18n.language

export default i18n
